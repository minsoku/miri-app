@dataclass(frozen=True)
class RiskParams:
    # 등급 컷오프 (0~100 위험점수 = 서울 전체 상권×업종 중 예상 폐업률 백분위)
    # POLICY: 상위 10% 고위험 / 10~30% 높음 / 30~60% 보통 / 하위 40% 낮음
    #   → 백테스트(검증 기간)에서 등급별 실제 1년 폐업률이 단조 증가하는지로 검증
    cut_normal: float = 40.0
    cut_high: float = 70.0
    cut_critical: float = 90.0
    coef_upper_bound: float = 3.0     # 요인 계수 상한 (과적합 방지)
    l2: float = 1e-3                  # 약한 릿지 규제


def risk_grade(score: float, p: RiskParams = RiskParams()) -> str:
    if score >= p.cut_critical:
        return "고위험"
    if score >= p.cut_high:
        return "높음"
    if score >= p.cut_normal:
        return "보통"
    return "낮음"


